-- BabyMonitor database initialization
-- Target: PostgreSQL database "bob", schema "babymonitor"
--
-- Run with:
--   PGPASSWORD=bob psql -h 127.0.0.1 -U bob -d bob -f db/init.sql
--
-- The script is idempotent: it can be re-run without duplicating rows.

CREATE SCHEMA IF NOT EXISTS babymonitor;

-- Application settings, addressed by tag.
CREATE TABLE IF NOT EXISTS babymonitor.settings (
    tag   VARCHAR(500) PRIMARY KEY,
    value VARCHAR(500) NOT NULL
);

-- Login accounts. password_hash is a bcrypt hash of the user's name
-- (sample data only -- never do this for real users).
CREATE TABLE IF NOT EXISTS babymonitor.users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(500) NOT NULL UNIQUE,
    password_hash VARCHAR(500) NOT NULL
);

-- Per-account UI preference: 'light', 'dark' or 'auto' (follow the OS). Set
-- from the Personal settings page and read on every login. Added in a separate
-- statement so an existing database picks the column up in place.
ALTER TABLE babymonitor.users
    ADD COLUMN IF NOT EXISTS theme VARCHAR(500) NOT NULL DEFAULT 'auto';

-- Per-account accent color: a Mantine palette name (blue, grape, teal, ...),
-- chosen from the "Theme Selection" swatches on the Personal settings page and
-- returned on every login.
ALTER TABLE babymonitor.users
    ADD COLUMN IF NOT EXISTS theme_color VARCHAR(500) NOT NULL DEFAULT 'blue';

-- Notifications raised by the device webhooks (see WebhookResource) and shown
-- on the Notifications page. `event_type` is the Video/Audio enum; `video_link`
-- is NULL for audio events.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1
                     FROM pg_type t
                     JOIN pg_namespace n ON n.oid = t.typnamespace
                    WHERE t.typname = 'event_type'
                      AND n.nspname = 'babymonitor') THEN
        CREATE TYPE babymonitor.event_type AS ENUM ('Video', 'Audio');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS babymonitor.notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time  TIMESTAMPTZ  NOT NULL,
    event_type  babymonitor.event_type NOT NULL,
    description VARCHAR(500) NOT NULL,
    video_link  VARCHAR(500)
);

-- Migration for databases created while `severity` and `read` were still part
-- of the table: drop them, add `event_type`, then classify the rows that are
-- left by whether they carry a clip. Rows from the retired demo set (still
-- without an event_type at this point) are removed so the feed stays coherent.
ALTER TABLE babymonitor.notifications
    DROP COLUMN IF EXISTS severity,
    DROP COLUMN IF EXISTS read,
    ADD COLUMN IF NOT EXISTS event_type babymonitor.event_type;

DELETE FROM babymonitor.notifications
 WHERE event_type IS NULL
   AND description IN (
       'Stream went offline: no frames received from the camera for 2 minutes.',
       'Motion detected in the crib.',
       'Nightly recording saved.');

UPDATE babymonitor.notifications
   SET event_type = (CASE WHEN video_link IS NULL THEN 'Audio' ELSE 'Video' END)::babymonitor.event_type
 WHERE event_type IS NULL;

ALTER TABLE babymonitor.notifications
    ALTER COLUMN event_type SET NOT NULL;

CREATE INDEX IF NOT EXISTS notifications_event_time_idx
    ON babymonitor.notifications (event_time DESC);

-- Per-account dismissal of a notification. A row here means "this account has
-- dismissed this notification", and the feed hides only those: the notification
-- itself is never deleted, so it stays visible (and on record) for everyone
-- else. The (notification, account) pair is the primary key, which makes
-- dismissing twice a no-op (INSERT ... ON CONFLICT DO NOTHING), and both
-- cascades keep the table clean if a notification or an account is removed.
CREATE TABLE IF NOT EXISTS babymonitor.notification_dismissals (
    notification_id BIGINT      NOT NULL
        REFERENCES babymonitor.notifications (id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL
        REFERENCES babymonitor.users (id) ON DELETE CASCADE,
    dismissed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (notification_id, user_id)
);

-- PostgreSQL does not index foreign keys, and deleting an account cascades into
-- this table, so it needs its own index on the account side. The feed needs no
-- further index: it probes the primary key by (notification_id, user_id).
CREATE INDEX IF NOT EXISTS notification_dismissals_user_idx
    ON babymonitor.notification_dismissals (user_id);

