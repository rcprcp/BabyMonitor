-- Ambient readings from the nursery sensor. A time series: one row per sample,
-- charted and listed on the Environment page. `event_time` follows the
-- notifications table's naming for the instant a sample was taken.
CREATE TABLE IF NOT EXISTS babymonitor.environment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time  TIMESTAMPTZ  NOT NULL,
    temperature NUMERIC(5,2) NOT NULL,
    humidity    NUMERIC(5,2) NOT NULL,
    brightness  INTEGER      NOT NULL
);

-- The Environment page always reads the newest samples first.
CREATE INDEX IF NOT EXISTS environment_event_time_idx
    ON babymonitor.environment (event_time DESC);

-- Test readings: one per hour for the last seven days, following a daily
-- rhythm (coolest just before dawn, warmest mid-afternoon, brightness peaking
-- around noon) plus a little deterministic jitter so the chart is not a pure
-- sine. Seeded only while the table is empty: the timestamps are relative to
-- now(), so re-running this script must not stack another week of rows on top.
-- Delete this statement if you ever want real readings only.
INSERT INTO babymonitor.environment (event_time, temperature, humidity, brightness)
SELECT sample.taken_at,
       round((21.5
              + 2.5 * sin(2 * pi() * (extract(hour FROM sample.taken_at) - 9) / 24)
              + (sample.n % 5 - 2) * 0.1)::numeric, 2),
       round((45.0
              - 8.0 * sin(2 * pi() * (extract(hour FROM sample.taken_at) - 9) / 24)
              + (sample.n % 7 - 3) * 0.3)::numeric, 2),
       (greatest(0, round(40000 * sin(pi() * (extract(hour FROM sample.taken_at) - 6) / 12)
              + (sample.n % 11) * 150)))::integer
  FROM (SELECT g AS n, now() - (g || ' hours')::interval AS taken_at
          FROM generate_series(0, 167) AS g) AS sample
 WHERE NOT EXISTS (SELECT 1 FROM babymonitor.environment);

-- Per-camera parameters, one row per (camera, parameter). `enabled` is the
-- camera's own on/off flag; because the table has no separate camera row it is
-- repeated on every parameter of that camera, so switching a camera on or off
-- updates all of its rows together. (camera_number, key) is the primary key, so
-- a camera cannot define the same parameter twice.
--
-- The parameter names are Motion option names: the app writes them, almost
-- verbatim, into the camera's generated motion.config.<n>. Both cameras are USB
-- cameras, so they are addressed by `video_device` (video4linux), not a network
-- URL. `enabled` on Camera 2 ships false so both states are visible.
CREATE TABLE IF NOT EXISTS babymonitor.cameras (
    camera_number INTEGER      NOT NULL,
    key           VARCHAR(500) NOT NULL,
    value         VARCHAR(500) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (camera_number, key)
);

