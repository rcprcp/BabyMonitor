package com.babymonitor.motion;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.LinkedHashMap;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * Unit tests for {@link MotionConfigBuilder} -- the one place a hand-edited
 * camera row becomes Motion config text, so the validation matters.
 */
class MotionConfigBuilderTest {

    private final MotionConfigBuilder builder = new MotionConfigBuilder();

    private static Map<String, String> parameters(String... pairs) {
        Map<String, String> parameters = new LinkedHashMap<>();
        for (int i = 0; i < pairs.length; i += 2) {
            parameters.put(pairs[i], pairs[i + 1]);
        }
        return parameters;
    }

    @Test
    void writesTheTemplateThenTheCameraParameters() {
        String config = builder.build(1, "daemon off\nlog_level 5", parameters(
                "camera_name", "Nursery",
                "width", "1280",
                "stream_port", "8081"));

        assertTrue(config.startsWith("# Generated by BabyMonitor for camera 1.\n"), config);
        assertTrue(config.contains("daemon off\nlog_level 5\n\n"), config);
        assertTrue(config.contains("# --- camera 1 parameters (babymonitor.cameras) ---\n"), config);
        assertTrue(config.contains("camera_name Nursery\n"), config);
        assertTrue(config.contains("width 1280\n"), config);
        assertTrue(config.contains("stream_port 8081\n"), config);
        assertTrue(config.endsWith("\n"), config);
    }

    @Test
    void ordersParametersByName() {
        String config = builder.build(1, null, parameters(
                "width", "1280",
                "camera_name", "Nursery",
                "height", "720"));

        int cameraName = config.indexOf("camera_name Nursery");
        int height = config.indexOf("height 720");
        int width = config.indexOf("width 1280");
        assertTrue(cameraName < height && height < width, config);
    }

    @Test
    void acceptsAValueWithSpaces() {
        String config = builder.build(2, null, parameters(
                "log_file", "/home/bob/motion/2/logs/motion.log",
                "movie_filename", "%Y%m%d-%H%M%S"));
        assertTrue(config.contains("movie_filename %Y%m%d-%H%M%S\n"), config);
    }

    @Test
    void aValueWithANewlineWouldInjectAnOptionAndIsRejected() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("camera_name", "Nursery\ndaemon on")));
    }

    @Test
    void aValueWithAControlCharacterIsRejected() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("camera_name", "Nursery\u0007")));
    }

    @Test
    void aKeyThatIsNotAMotionOptionNameIsRejected() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("not a key", "x")));
    }

    @Test
    void aBlankValueIsRejected() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("camera_name", "  ")));
    }

    @Test
    void numericOptionsAreChecked() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("width", "wide")));
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("framerate", "0")));
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("stream_port", "70000")));
    }

    @Test
    void booleanOptionsAreChecked() {
        assertThrows(IllegalArgumentException.class,
                () -> builder.build(1, null, parameters("stream_localhost", "maybe")));
        String config = builder.build(1, null, parameters("stream_localhost", "off"));
        assertTrue(config.contains("stream_localhost off\n"), config);
    }

    @Test
    void keepsTheGivenOrderForEverythingElse() {
        // A camera with no parameters still yields the header.
        String config = builder.build(2, null, Map.of());
        assertEquals(
                "# Generated by BabyMonitor for camera 2.\n"
                        + "# Built from babymonitor.cameras -- edit the values on the Camera 2 page.\n"
                        + "# Do not edit this file: it is rewritten on every Apply.\n\n"
                        + "# --- camera 2 parameters (babymonitor.cameras) ---\n",
                config);
    }
}
