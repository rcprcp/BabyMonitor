package com.babymonitor.motion;

import jakarta.enterprise.context.ApplicationScoped;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.regex.Pattern;

/**
 * Turns one camera's parameters into a complete Motion configuration file.
 *
 * <p>Motion has no {@code include} directive, so the file must be self
 * contained: this prepends the shared template and then appends one
 * {@code key value} line per camera parameter. Motion applies the settings in
 * file order and the last one wins, so the per-camera rows override the
 * template's defaults.
 *
 * <p>The camera parameter names <em>are</em> Motion option names, so the mapping
 * is a near pass-through. The one place that matters is validation: the values
 * are edited by hand on the Camera pages, and a newline would let a value inject
 * a second option, so every value is checked here before it reaches the file.
 */
@ApplicationScoped
public class MotionConfigBuilder {

    private static final Pattern KEY_PATTERN = Pattern.compile("[a-z][a-z0-9_]*");
    private static final int MAX_VALUE_LENGTH = 500;
    private static final Set<String> BOOLEAN_KEYS = Set.of("stream_localhost", "webcontrol_localhost");
    private static final Set<String> SIZE_KEYS = Set.of("width", "height");
    private static final Set<String> FRAMERATE_KEYS = Set.of("framerate");
    private static final Set<String> PORT_KEYS = Set.of("stream_port", "webcontrol_port");
    private static final Set<String> BOOLEANS = Set.of("on", "off", "yes", "no", "true", "false", "1", "0");

    /**
     * Builds the config file for one camera.
     *
     * @param cameraNumber the camera the file is for
     * @param template     the shared base config, or {@code null}/blank for none
     * @param parameters   the camera's rows, keyed by Motion option name
     * @return the complete file contents, ending in a newline
     * @throws IllegalArgumentException when a key or value cannot safely be written
     */
    public String build(int cameraNumber, String template, Map<String, String> parameters) {
        StringBuilder config = new StringBuilder();
        config.append("# Generated by BabyMonitor for camera ").append(cameraNumber).append(".\n");
        config.append("# Built from babymonitor.cameras -- edit the values on the Camera ")
                .append(cameraNumber).append(" page.\n");
        config.append("# Do not edit this file: it is rewritten on every Apply.\n\n");
        if (template != null && !template.isBlank()) {
            config.append(template.strip()).append("\n\n");
        }
        config.append("# --- camera ").append(cameraNumber)
                .append(" parameters (babymonitor.cameras) ---\n");
        for (Map.Entry<String, String> parameter : new TreeMap<>(parameters).entrySet()) {
            String key = parameter.getKey();
            config.append(key).append(' ').append(validate(key, parameter.getValue())).append('\n');
        }
        return config.toString();
    }

    private static String validate(String key, String rawValue) {
        if (key == null || !KEY_PATTERN.matcher(key).matches()) {
            throw new IllegalArgumentException("Not a Motion option name: " + key);
        }
        if (rawValue == null) {
            throw new IllegalArgumentException(key + " has no value");
        }
        String value = rawValue.strip();
        if (value.isEmpty()) {
            throw new IllegalArgumentException(key + " has no value");
        }
        if (value.length() > MAX_VALUE_LENGTH) {
            throw new IllegalArgumentException(key + " is longer than " + MAX_VALUE_LENGTH + " characters");
        }
        for (int i = 0; i < value.length(); i++) {
            if (value.charAt(i) < 0x20) {
                throw new IllegalArgumentException(key + " may not contain control characters");
            }
        }

        if (BOOLEAN_KEYS.contains(key)) {
            if (!BOOLEANS.contains(value.toLowerCase(Locale.ROOT))) {
                throw new IllegalArgumentException(key + " must be on or off");
            }
        } else if (PORT_KEYS.contains(key)) {
            if (positiveInt(key, value) > 65535) {
                throw new IllegalArgumentException(key + " must be between 1 and 65535");
            }
        } else if (SIZE_KEYS.contains(key)) {
            if (positiveInt(key, value) > 10000) {
                throw new IllegalArgumentException(key + " must be between 1 and 10000");
            }
        } else if (FRAMERATE_KEYS.contains(key)) {
            if (positiveInt(key, value) > 240) {
                throw new IllegalArgumentException(key + " must be between 1 and 240");
            }
        }
        return value;
    }

    private static int positiveInt(String key, String value) {
        try {
            int parsed = Integer.parseInt(value);
            if (parsed < 1) {
                throw new NumberFormatException();
            }
            return parsed;
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException(key + " must be a positive whole number");
        }
    }
}
