-- BabyMonitor schema.
--
-- Flyway owns the schema. This first migration is the state a database created
-- by the retired db/init.sql already had, which is what lets an existing
-- database be baselined at V1 and then brought forward by the later migrations
-- instead of being recreated (see quarkus.flyway.baseline-on-migrate in
-- application.properties). A fresh database runs V1, V2 and V3 in order.
--
-- Everything here is schema only; the seed rows live in V2__seed_data.sql.

CREATE SCHEMA IF NOT EXISTS babymonitor;

-- Application settings, addressed by tag.
CREATE TABLE babymonitor.settings (
    tag   VARCHAR(500) PRIMARY KEY,
    value VARCHAR(500) NOT NULL
);

-- Login accounts. password_hash is a bcrypt hash of the user's name for the
-- sample accounts (seed data only -- never do this for real users).
CREATE TABLE babymonitor.users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(500) NOT NULL UNIQUE,
    password_hash VARCHAR(500) NOT NULL,
    -- Per-account UI preference: 'light', 'dark' or 'auto' (follow the OS).
    theme         VARCHAR(500) NOT NULL DEFAULT 'auto',
    -- Per-account accent color: a Mantine palette name (blue, grape, teal, ...).
    theme_color   VARCHAR(500) NOT NULL DEFAULT 'blue',
    -- Per-account alert-sound choice: a file prefix in frontend/public/sounds/.
    prompt_sound  VARCHAR(500) NOT NULL DEFAULT 'chime'
);

-- Notifications raised by the device webhooks (see WebhookResource) and by the
-- Motion supervisor, and shown on the Notifications page. `event_type` is the
-- Video/Audio/System enum; `video_link` is NULL for audio and system events.
CREATE TYPE babymonitor.event_type AS ENUM ('Video', 'Audio');

CREATE TABLE babymonitor.notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time  TIMESTAMPTZ  NOT NULL,
    event_type  babymonitor.event_type NOT NULL,
    description VARCHAR(500) NOT NULL,
    video_link  VARCHAR(500)
);

-- The feed always reads the newest events first.
CREATE INDEX notifications_event_time_idx
    ON babymonitor.notifications (event_time DESC);

-- Per-account dismissal of a notification. A row here means "this account has
-- dismissed this notification", and the feed hides only those: the notification
-- itself is never deleted, so it stays visible (and on record) for everyone
-- else. The (notification, account) pair is the primary key, which makes
-- dismissing twice a no-op (INSERT ... ON CONFLICT DO NOTHING), and both
-- cascades keep the table clean if a notification or an account is removed.
CREATE TABLE babymonitor.notification_dismissals (
    notification_id BIGINT      NOT NULL
        REFERENCES babymonitor.notifications (id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL
        REFERENCES babymonitor.users (id) ON DELETE CASCADE,
    dismissed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (notification_id, user_id)
);

-- PostgreSQL does not index foreign keys, and deleting an account cascades into
-- this table, so it needs its own index on the account side. The feed needs no
-- further index: it probes the primary key by (notification_id, user_id).
CREATE INDEX notification_dismissals_user_idx
    ON babymonitor.notification_dismissals (user_id);

-- Ambient readings from the nursery sensor. A time series: one row per sample,
-- charted and listed on the Environment page. `event_time` follows the
-- notifications table's naming for the instant a sample was taken.
CREATE TABLE babymonitor.environment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_time  TIMESTAMPTZ  NOT NULL,
    temperature NUMERIC(5,2) NOT NULL,
    humidity    NUMERIC(5,2) NOT NULL,
    brightness  INTEGER      NOT NULL
);

-- The Environment page always reads the newest samples first.
CREATE INDEX environment_event_time_idx
    ON babymonitor.environment (event_time DESC);

-- Per-camera parameters, one row per (camera, parameter). `enabled` is the
-- camera's persisted desired state -- TRUE means "this camera should be
-- running" -- and is repeated on every parameter of that camera because the
-- table has no separate camera row, so it is written to all of them together.
-- The Motion supervisor reads it to decide which cameras to keep alive.
-- (camera_number, key) is the primary key, so a camera cannot define the same
-- parameter twice.
CREATE TABLE babymonitor.cameras (
    camera_number INTEGER      NOT NULL,
    key           VARCHAR(500) NOT NULL,
    value         VARCHAR(500) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    PRIMARY KEY (camera_number, key)
);
